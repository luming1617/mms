#!/usr/bin/env python3
"""OpenAPI contract regression gate.

Compares the schema generated by the running FastAPI app with the published
baseline in contracts/openapi-baseline.json and classifies changes as
breaking, warning or info.

Usage:
    python scripts/openapi_contract.py --write
    python scripts/openapi_contract.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

DEFAULT_BASELINE = ROOT / "contracts" / "openapi-baseline.json"
HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
BREAKING = "breaking"
WARNING = "warning"
INFO = "info"


@dataclass(frozen=True)
class Change:
    kind: str
    location: str
    message: str

    def as_dict(self) -> dict[str, str]:
        return {"kind": self.kind, "location": self.location, "message": self.message}


def load_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return payload


def current_spec() -> dict[str, Any]:
    from mms.api.main import app

    return app.openapi()


def _pointer(spec: dict[str, Any], ref: str) -> Any:
    if not ref.startswith("#/"):
        return None
    node: Any = spec
    for raw_part in ref[2:].split("/"):
        part = raw_part.replace("~1", "/").replace("~0", "~")
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def resolve(spec: dict[str, Any], node: Any, seen: frozenset[str] = frozenset()) -> Any:
    if not isinstance(node, dict) or "$ref" not in node:
        return node
    ref = node["$ref"]
    if not isinstance(ref, str) or ref in seen:
        return node
    target = _pointer(spec, ref)
    if target is None:
        return node
    resolved = resolve(spec, target, seen | {ref})
    siblings = {key: value for key, value in node.items() if key != "$ref"}
    if not siblings or not isinstance(resolved, dict):
        return resolved
    merged = dict(resolved)
    merged.update(siblings)
    return merged


def flatten(spec: dict[str, Any], schema: Any, seen: frozenset[str] = frozenset()) -> dict[str, Any]:
    """Resolve $ref and merge allOf branches into one comparison-friendly schema."""
    resolved = resolve(spec, schema, seen)
    if not isinstance(resolved, dict):
        return {}
    result: dict[str, Any] = {}
    branches = resolved.get("allOf")
    if isinstance(branches, list):
        for branch in branches:
            merged = flatten(spec, branch, seen | {resolved.get("$ref", "")})
            for key, value in merged.items():
                if key == "required":
                    result[key] = sorted(set(result.get(key, [])) | set(value))
                elif key == "properties":
                    result[key] = {**result.get(key, {}), **value}
                else:
                    result.setdefault(key, value)
    for key, value in resolved.items():
        if key == "allOf":
            continue
        if key == "required":
            result[key] = sorted(set(result.get(key, [])) | set(value))
        elif key == "properties":
            result[key] = {**result.get(key, {}), **value}
        else:
            result[key] = value
    return result


def _as_set(value: Any) -> set[Any]:
    if value is None:
        return set()
    if isinstance(value, list):
        return set(value)
    return {value}


def _type_set(schema: dict[str, Any]) -> set[str]:
    raw = schema.get("type")
    if raw is None:
        return set()
    return {str(item) for item in raw} if isinstance(raw, list) else {str(raw)}


def _location(base: str, name: str) -> str:
    return f"{base}/{name}"


def _compare_constraints(
    old: dict[str, Any], new: dict[str, Any], spec: dict[str, Any], location: str, direction: str, changes: list[Change]
) -> None:
    tighter: list[str] = []
    for key in ("minimum", "exclusiveMinimum", "minLength", "minItems", "multipleOf"):
        if (
            key in old
            and key in new
            and isinstance(old[key], int | float)
            and isinstance(new[key], int | float)
            and new[key] > old[key]
        ):
            tighter.append(f"{key} {old[key]} -> {new[key]}")
    for key in ("maximum", "exclusiveMaximum", "maxLength", "maxItems"):
        if (
            key in old
            and key in new
            and isinstance(old[key], int | float)
            and isinstance(new[key], int | float)
            and new[key] < old[key]
        ):
            tighter.append(f"{key} {old[key]} -> {new[key]}")
    if "pattern" in old and "pattern" in new and old["pattern"] != new["pattern"]:
        tighter.append(f"pattern {old['pattern']!r} -> {new['pattern']!r}")
    for detail in tighter:
        if direction == "request":
            changes.append(Change(BREAKING, location, f"request constraint tightened: {detail}"))
        else:
            changes.append(Change(WARNING, location, f"response constraint changed: {detail}"))
    if "additionalProperties" in old or "additionalProperties" in new:
        old_ap = old.get("additionalProperties", True)
        new_ap = new.get("additionalProperties", True)
        if old_ap is True and new_ap is False:
            changes.append(Change(BREAKING, location, "additionalProperties changed from allowed to forbidden"))
        elif old_ap is False and new_ap is True:
            changes.append(Change(INFO, location, "additionalProperties relaxed to allowed"))
    old_nullable = bool(old.get("nullable", False))
    new_nullable = bool(new.get("nullable", False))
    if old_nullable and not new_nullable:
        changes.append(Change(BREAKING, location, "field is no longer nullable"))
    elif not old_nullable and new_nullable:
        changes.append(Change(INFO, location, "field is now nullable"))


def compare_schema(
    spec: dict[str, Any], old_schema: Any, new_schema: Any, location: str, direction: str, changes: list[Change]
) -> None:
    old = flatten(spec, old_schema)
    new = flatten(spec, new_schema)
    if old == new:
        return
    old_types = _type_set(old)
    new_types = _type_set(new)
    if old_types != new_types:
        changes.append(
            Change(
                BREAKING,
                location,
                f"type changed: {sorted(old_types) or 'unspecified'} -> {sorted(new_types) or 'unspecified'}",
            )
        )
    old_enum = _as_set(old.get("enum"))
    new_enum = _as_set(new.get("enum"))
    if old_enum != new_enum:
        removed = sorted(old_enum - new_enum, key=str)
        added = sorted(new_enum - old_enum, key=str)
        if removed:
            changes.append(Change(BREAKING, _location(location, "enum"), f"allowed values removed: {removed}"))
        if added:
            changes.append(Change(INFO, _location(location, "enum"), f"allowed values added: {added}"))
    old_required = set(old.get("required", []))
    new_required = set(new.get("required", []))
    for name in sorted(new_required - old_required):
        changes.append(Change(BREAKING, _location(location, f"required/{name}"), f"new required {direction} field"))
    for name in sorted(old_required - new_required):
        changes.append(
            Change(INFO, _location(location, f"required/{name}"), f"{direction} field is no longer required")
        )
    old_props = old.get("properties") if isinstance(old.get("properties"), dict) else {}
    new_props = new.get("properties") if isinstance(new.get("properties"), dict) else {}
    for name in sorted(set(old_props) - set(new_props)):
        changes.append(Change(BREAKING, _location(location, f"properties/{name}"), f"{direction} property removed"))
    for name in sorted(set(new_props) - set(old_props)):
        if name in new_required:
            continue
        changes.append(Change(INFO, _location(location, f"properties/{name}"), f"optional {direction} property added"))
    for name in sorted(set(old_props) & set(new_props)):
        compare_schema(
            spec, old_props[name], new_props[name], _location(location, f"properties/{name}"), direction, changes
        )
    if "items" in old or "items" in new:
        compare_schema(
            spec, old.get("items", {}), new.get("items", {}), _location(location, "items"), direction, changes
        )
    for combinator in ("oneOf", "anyOf"):
        if combinator in old or combinator in new:
            old_branches = old.get(combinator, [])
            new_branches = new.get(combinator, [])
            if _canonical(old_branches) != _canonical(new_branches):
                changes.append(
                    Change(
                        WARNING,
                        _location(location, combinator),
                        f"{combinator} branches changed; review compatibility manually",
                    )
                )
    _compare_constraints(old, new, spec, location, direction, changes)


def _canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, ensure_ascii=False, default=str)


def _compare_parameters(
    spec: dict[str, Any], old_op: dict[str, Any], new_op: dict[str, Any], location: str, changes: list[Change]
) -> None:
    def collect(operation: dict[str, Any]) -> dict[tuple[str, str], dict[str, Any]]:
        result: dict[tuple[str, str], dict[str, Any]] = {}
        for raw in operation.get("parameters", []) or []:
            param = resolve(spec, raw)
            if isinstance(param, dict) and "name" in param and "in" in param:
                result[(str(param["name"]), str(param["in"]))] = param
        return result

    old_params = collect(old_op)
    new_params = collect(new_op)
    for key in sorted(set(old_params) - set(new_params)):
        changes.append(Change(BREAKING, f"{location}/parameters/{key[1]}/{key[0]}", "parameter removed"))
    for key in sorted(set(new_params) - set(old_params)):
        if new_params[key].get("required"):
            changes.append(Change(BREAKING, f"{location}/parameters/{key[1]}/{key[0]}", "new required parameter"))
        else:
            changes.append(Change(INFO, f"{location}/parameters/{key[1]}/{key[0]}", "optional parameter added"))
    for key in sorted(set(old_params) & set(new_params)):
        old_param = old_params[key]
        new_param = new_params[key]
        param_location = f"{location}/parameters/{key[1]}/{key[0]}"
        if not old_param.get("required") and new_param.get("required"):
            changes.append(Change(BREAKING, param_location, "parameter became required"))
        compare_schema(
            spec, old_param.get("schema", {}), new_param.get("schema", {}), param_location, "request", changes
        )


def _compare_content(
    spec: dict[str, Any],
    old_content: Any,
    new_content: Any,
    location: str,
    direction: str,
    changes: list[Change],
) -> None:
    old_media = old_content if isinstance(old_content, dict) else {}
    new_media = new_content if isinstance(new_content, dict) else {}
    for media in sorted(set(old_media) - set(new_media)):
        changes.append(Change(BREAKING, f"{location}/content/{media}", f"{direction} media type removed"))
    for media in sorted(set(new_media) - set(old_media)):
        changes.append(Change(INFO, f"{location}/content/{media}", f"{direction} media type added"))
    for media in sorted(set(old_media) & set(new_media)):
        old_schema = old_media[media].get("schema", {}) if isinstance(old_media[media], dict) else {}
        new_schema = new_media[media].get("schema", {}) if isinstance(new_media[media], dict) else {}
        if _canonical(old_schema) != _canonical(new_schema):
            compare_schema(spec, old_schema, new_schema, f"{location}/content/{media}/schema", direction, changes)


def _compare_operations(
    spec: dict[str, Any], old_op: dict[str, Any], new_op: dict[str, Any], location: str, changes: list[Change]
) -> None:
    _compare_parameters(spec, old_op, new_op, location, changes)
    old_body = resolve(spec, old_op.get("requestBody", {}))
    new_body = resolve(spec, new_op.get("requestBody", {}))
    if old_body or new_body:
        if old_body and not new_body:
            changes.append(Change(BREAKING, f"{location}/requestBody", "request body removed"))
        elif new_body and not old_body:
            changes.append(Change(BREAKING, f"{location}/requestBody", "request body added"))
        else:
            if not old_body.get("required") and new_body.get("required"):
                changes.append(Change(BREAKING, f"{location}/requestBody", "request body became required"))
            _compare_content(
                spec, old_body.get("content"), new_body.get("content"), f"{location}/requestBody", "request", changes
            )
    old_responses = old_op.get("responses", {}) if isinstance(old_op.get("responses"), dict) else {}
    new_responses = new_op.get("responses", {}) if isinstance(new_op.get("responses"), dict) else {}
    for code in sorted(set(old_responses) - set(new_responses)):
        changes.append(Change(BREAKING, f"{location}/responses/{code}", "response status code removed"))
    for code in sorted(set(new_responses) - set(old_responses)):
        changes.append(Change(INFO, f"{location}/responses/{code}", "response status code added"))
    for code in sorted(set(old_responses) & set(new_responses)):
        old_response = resolve(spec, old_responses[code])
        new_response = resolve(spec, new_responses[code])
        _compare_content(
            spec,
            old_response.get("content"),
            new_response.get("content"),
            f"{location}/responses/{code}",
            "response",
            changes,
        )
    if _canonical(old_op.get("security")) != _canonical(new_op.get("security")):
        changes.append(Change(WARNING, f"{location}/security", "operation security requirements changed"))
    if not old_op.get("deprecated") and new_op.get("deprecated"):
        changes.append(Change(WARNING, f"{location}/deprecated", "operation marked deprecated"))


def compare_specs(baseline: dict[str, Any], current: dict[str, Any]) -> list[Change]:
    changes: list[Change] = []
    old_paths = baseline.get("paths", {}) if isinstance(baseline.get("paths"), dict) else {}
    new_paths = current.get("paths", {}) if isinstance(current.get("paths"), dict) else {}
    for path in sorted(set(old_paths) - set(new_paths)):
        changes.append(Change(BREAKING, f"paths/{path}", "path removed"))
    for path in sorted(set(new_paths) - set(old_paths)):
        changes.append(Change(INFO, f"paths/{path}", "path added"))
    for path in sorted(set(old_paths) & set(new_paths)):
        old_item = old_paths[path] if isinstance(old_paths[path], dict) else {}
        new_item = new_paths[path] if isinstance(new_paths[path], dict) else {}
        for method in HTTP_METHODS:
            location = f"paths/{path}/{method}"
            if method in old_item and method not in new_item:
                changes.append(Change(BREAKING, location, "operation removed"))
            elif method not in old_item and method in new_item:
                changes.append(Change(INFO, location, "operation added"))
            elif method in old_item and method in new_item:
                _compare_operations(current, old_item[method], new_item[method], location, changes)
    old_schemes = baseline.get("components", {}).get("securitySchemes", {})
    new_schemes = current.get("components", {}).get("securitySchemes", {})
    for name in sorted(set(old_schemes) - set(new_schemes)):
        changes.append(Change(BREAKING, f"components/securitySchemes/{name}", "security scheme removed"))
    for name in sorted(set(old_schemes) & set(new_schemes)):
        if _canonical(old_schemes[name]) != _canonical(new_schemes[name]):
            changes.append(Change(BREAKING, f"components/securitySchemes/{name}", "security scheme changed"))
    if _canonical(baseline.get("servers")) != _canonical(current.get("servers")):
        changes.append(Change(WARNING, "servers", "server list changed"))
    old_version = baseline.get("info", {}).get("version")
    new_version = current.get("info", {}).get("version")
    if old_version != new_version:
        changes.append(Change(INFO, "info/version", f"API version {old_version} -> {new_version}"))
    return changes


def _dedupe(changes: list[Change]) -> list[Change]:
    seen: set[tuple[str, str, str]] = set()
    unique: list[Change] = []
    for change in changes:
        key = (change.kind, change.location, change.message)
        if key not in seen:
            seen.add(key)
            unique.append(change)
    return sorted(
        unique, key=lambda item: ({"breaking": 0, "warning": 1, "info": 2}[item.kind], item.location, item.message)
    )


def _counts(changes: list[Change]) -> dict[str, int]:
    return {kind: sum(1 for change in changes if change.kind == kind) for kind in (BREAKING, WARNING, INFO)}


def _print_text(changes: list[Change], counts: dict[str, int]) -> None:
    for change in changes:
        print(f"[{change.kind.upper():8}] {change.location}: {change.message}")
    print(f"summary: {counts[BREAKING]} breaking, {counts[WARNING]} warning, {counts[INFO]} info")


def main() -> int:
    parser = argparse.ArgumentParser(description="Check FastAPI OpenAPI schema against the published baseline")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="write the current schema as the new baseline")
    action.add_argument("--check", action="store_true", help="compare the current schema with the baseline")
    parser.add_argument("--baseline", type=Path, default=DEFAULT_BASELINE)
    parser.add_argument("--json-report", type=Path, help="write a machine-readable report")
    parser.add_argument("--allow-breaking", action="store_true", help="report breaking changes but exit 0")
    parser.add_argument("--warnings-as-errors", action="store_true")
    args = parser.parse_args()

    spec = current_spec()
    if args.write:
        args.baseline.parent.mkdir(parents=True, exist_ok=True)
        args.baseline.write_text(
            json.dumps(spec, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        print(f"wrote OpenAPI baseline: {args.baseline}")
        return 0
    if not args.baseline.is_file():
        print(f"baseline not found: {args.baseline}; run --write to publish the current contract", file=sys.stderr)
        return 2
    baseline = load_json(args.baseline)
    changes = _dedupe(compare_specs(baseline, spec))
    counts = _counts(changes)
    if args.json_report:
        args.json_report.parent.mkdir(parents=True, exist_ok=True)
        args.json_report.write_text(
            json.dumps(
                {
                    "generated_at": datetime.now(UTC).isoformat(),
                    "baseline": str(args.baseline),
                    "info_version": spec.get("info", {}).get("version"),
                    "counts": counts,
                    "changes": [change.as_dict() for change in changes],
                },
                ensure_ascii=False,
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
    _print_text(changes, counts)
    failed = counts[BREAKING] > 0 and not args.allow_breaking
    failed = failed or (args.warnings_as_errors and counts[WARNING] > 0)
    return 2 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
